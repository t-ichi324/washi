<?php

namespace Washi;

/**
 * Autoloader for the app's lib/ folder (registered by App; apps never call this directly).
 *
 *   lib/Models/Shisetsu.php      class Shisetsu            ← 名前空間なし: lib/ 配下をファイル名で再帰的に探す
 *   lib/Services/Mailer.php      class Mailer
 *   lib/Models/Note.php          namespace App\Models;     ← 名前空間つき: lib/App/Models/Note.php、先頭を剥がした
 *   lib/Vendor/Acme/Client.php   namespace Acme;              lib/Models/Note.php を先に見て、無ければファイル名で探す
 *
 * Folder names are free. A class name without namespace must be unique in lib/ (any folder): when two files share
 * the name, loading it throws instead of silently picking one. Give one of them a namespace to resolve it.
 *
 * The "file name → paths" map is built on the first lookup. In production it is cached in storage/cache/lib-classmap.php;
 * a class missing from the cache or a cached path that no longer exists triggers one rebuild per request, so moving
 * or adding files needs no manual step. `$app->clearClassMap()` deletes the cache anyway. In debug it is never cached.
 */
final class LibAutoloader
{
    /** @var array<string,list<string>>|null ファイル名（拡張子なし） → 絶対パス */
    private ?array $map = null;
    private bool $rebuilt = false;

    public function __construct(private readonly string $dir, private readonly ?string $cacheFile = null) {}

    public function register(): void
    {
        if (is_dir($this->dir)) spl_autoload_register($this->load(...));
    }

    public function load(string $class): void
    {
        $rel = str_replace('\\', '/', ltrim($class, '\\'));
        if (($pos = strpos($rel, '/')) !== false) {
            // 名前空間つきは従来どおりパスで探す（App\Models\User → lib/App/Models/User.php, lib/Models/User.php）
            foreach (["{$this->dir}/$rel.php", "{$this->dir}/" . substr($rel, $pos + 1) . '.php'] as $f) {
                if (is_file($f)) { require_once $f; return; }
            }
        }
        $file = $this->find(basename($rel));
        if ($file !== null) require_once $file;
    }

    /** 対応表のキャッシュを消す（次の読み込みで作り直す） */
    public function clear(): void
    {
        $this->map = null;
        $this->rebuilt = false;
        if ($this->cacheFile !== null && is_file($this->cacheFile)) @unlink($this->cacheFile);
    }

    private function find(string $name): ?string
    {
        $paths = $this->map()[$name] ?? null;
        $stale = $paths !== null && array_filter($paths, static fn($p) => !is_file($p));
        if (($paths === null || $stale) && !$this->rebuilt) {
            $this->rebuild();
            $paths = $this->map[$name] ?? null;
        }
        $paths = array_values(array_filter($paths ?? [], 'is_file'));   // このリクエストで作り直し済みでも消えたファイルは読まない
        if (!$paths) return null;
        if (count($paths) > 1) {
            throw new \LogicException("Class name '$name' is defined by more than one file in lib/: " . implode(', ', $paths)
                . '. Class names without a namespace must be unique in lib/ — give one of them a namespace.');
        }
        return $paths[0];
    }

    /** @return array<string,list<string>> */
    private function map(): array
    {
        if ($this->map !== null) return $this->map;
        if ($this->cacheFile !== null && is_file($this->cacheFile)) {
            $cached = @include $this->cacheFile;
            if (is_array($cached)) return $this->map = $cached;
        }
        return $this->rebuild();
    }

    /** @return array<string,list<string>> */
    private function rebuild(): array
    {
        $this->rebuilt = true;
        $map = [];
        $it = new \RecursiveIteratorIterator(new \RecursiveCallbackFilterIterator(
            new \RecursiveDirectoryIterator($this->dir, \FilesystemIterator::SKIP_DOTS),
            // .git などの隠しフォルダは見ない。ファイルはクラス名として正しい名前の .php だけ
            static fn(\SplFileInfo $f) => $f->getFilename()[0] !== '.'
                && ($f->isDir() || preg_match('/^[A-Za-z_][A-Za-z0-9_]*\.php$/', $f->getFilename())),
        ));
        foreach ($it as $f) $map[$f->getBasename('.php')][] = str_replace('\\', '/', $f->getPathname());
        foreach ($map as &$paths) sort($paths);
        unset($paths);
        ksort($map);
        $this->map = $map;

        if ($this->cacheFile !== null) {
            // 書けなくても動作は変わらない（毎回作るだけ）。別リクエストと競合しないよう tmp → rename
            $dir = dirname($this->cacheFile);
            if (is_dir($dir) || @mkdir($dir, 0775, true)) {
                $tmp = $this->cacheFile . '.' . getmypid() . '.tmp';
                if (@file_put_contents($tmp, "<?php\n// generated by Washi\\LibAutoloader — safe to delete\nreturn " . var_export($map, true) . ";\n") !== false) {
                    @rename($tmp, $this->cacheFile);
                    if (function_exists('opcache_invalidate')) @opcache_invalidate($this->cacheFile, true);
                }
            }
        }
        return $map;
    }
}
